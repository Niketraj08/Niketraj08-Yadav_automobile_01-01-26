public class increment {
    public static void main(String[] args) {
        int i = 56;
        int j = 67;
        int c = ++j;

        System.out.println(i++);
        System.out.println(i);
        System.out.println(++i);
        System.out.println(i);
        System.out.println(i * c);
    }
}
